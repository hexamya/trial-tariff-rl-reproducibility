"""Fix the S0 household and month splits for the LCL response model and check balance.

Run:  python scripts/build_lcl_split.py      (needs scripts/build_lcl_panel.py first)

Writes data/processed/lcl_split.csv (not in git; regenerated from code) and
outputs/lcl_split_summary.md. Balance is checked on pre-trial data only (Jul-Dec 2012):
trial-period outcomes of held-out households are not looked at here.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from ttrl.analysis import lcl_did as did
from ttrl.data import lcl_features as lf
from ttrl.data import lcl_meters as lm
from ttrl.data import splits as sp
from ttrl.paths import OUTPUTS, PROCESSED
from ttrl.reporting import md_table

FIRST, LAST = "2012-07-01 00:30", "2014-02-28 00:00"
GROUP = {False: "Std", True: "dToU"}


def pre_trial_means(cal: pd.DataFrame) -> pd.DataFrame:
    """Mean kWh per half-hour of each household over the pre-trial calendar rows."""
    con = lm.connect()
    pre = cal.loc[cal["period"] == "pre", ["ts_label"]]
    con.register("pre_df", pre)
    return con.execute(f"""
        SELECT m.hh_id, avg(m.kwh) AS pre_kwh
        FROM read_parquet('{lm.PANEL_PATH.as_posix()}') m JOIN pre_df USING (ts_label)
        WHERE m.kwh IS NOT NULL GROUP BY m.hh_id""").df()


def balance_table(df: pd.DataFrame, col: str, n_boot: int = 2000, seed: int = 0) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = []
    for tou in (False, True):
        a = df.loc[(df["tou"] == tou) & (df["split"] == "train"), col].dropna().to_numpy()
        b = df.loc[(df["tou"] == tou) & (df["split"] == "holdout"), col].dropna().to_numpy()
        diff = b.mean() - a.mean()
        boot = [rng.choice(b, len(b)).mean() - rng.choice(a, len(a)).mean() for _ in range(n_boot)]
        lo, hi = np.percentile(boot, [2.5, 97.5])
        rows.append({"group": GROUP[tou], "train n": len(a), "holdout n": len(b), "train mean": a.mean(),
                     "holdout mean": b.mean(), "holdout - train": diff, "95% CI": f"[{lo:+.4f}, {hi:+.4f}]"})
    return pd.DataFrame(rows)


def fold_table(cal: pd.DataFrame) -> pd.DataFrame:
    trial = cal[cal["period"] == "trial"].reset_index(drop=True)
    ev = lf.find_events(trial)
    ev["fold"] = ev["start"].dt.month.map(sp.MONTH_FOLDS)
    trial["fold"] = sp.month_fold(trial["ts_local"])
    rows = []
    for f in sp.FOLDS:
        months = [m for m, k in sp.MONTH_FOLDS.items() if k == f]
        e, t = ev[ev["fold"] == f], trial[trial["fold"] == f]
        rows.append({"fold": f, "months": ", ".join(pd.Timestamp(2013, m, 1).strftime("%b") for m in months),
                     "High events": int((e["band"] == "High").sum()), "Low events": int((e["band"] == "Low").sum()),
                     "High half-hours": int((t["band"] == "High").sum()),
                     "Low half-hours": int((t["band"] == "Low").sum())})
    return pd.DataFrame(rows)


def main() -> None:
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    hh = lm.households()
    split = sp.household_split(hh)
    split.to_csv(PROCESSED / "lcl_split.csv", index=False)
    digest = sp.split_digest(split)

    cal = did.calendar(FIRST, LAST)
    cov = did.coverage(cal)
    sample = did.select_households(cov).merge(split[["hh_id", "split"]], on="hh_id")
    df = cov.merge(split[["hh_id", "split"]], on="hh_id").merge(pre_trial_means(cal), on="hh_id", how="left")

    counts = split.assign(group=split["tou"].map(GROUP)).pivot_table(
        index="group", columns="split", values="hh_id", aggfunc="count")
    counts_s = sample.assign(group=sample["tou"].map(GROUP)).pivot_table(
        index="group", columns="split", values="hh_id", aggfunc="count")

    report = "\n".join([
        "# LCL S0 splits: held-out households and month folds",
        "",
        "Generated by `python scripts/build_lcl_split.py`. Rules in `src/ttrl/data/splits.py`. Balance is checked on "
        "pre-trial data only; trial-period outcomes of held-out households were not looked at.",
        "",
        "## Households",
        "",
        f"{sp.HOLDOUT_SHARE:.0%} of each group held out, drawn with seed {sp.SPLIT_SEED} from the panel's household "
        f"table ({len(split):,} households). Digest `{digest}` (pinned in `tests/test_splits.py`).",
        "",
        "All households:",
        "",
        md_table(counts.reset_index(), floatfmt="{:.0f}"),
        "",
        "Main DiD sample (>= 80% pre-trial and >= 90% trial coverage):",
        "",
        md_table(counts_s.reset_index(), floatfmt="{:.0f}"),
        "",
        "## Balance on pre-trial information (Jul-Dec 2012)",
        "",
        "Mean kWh per half-hour, households with pre-trial readings (bootstrap 95% CI of the difference):",
        "",
        md_table(balance_table(df, "pre_kwh"), floatfmt="{:.4f}"),
        "",
        "Share of pre-trial half-hours with a reading:",
        "",
        md_table(balance_table(df, "pre"), floatfmt="{:.4f}"),
        "",
        "## Month folds (2013)",
        "",
        "Each fold takes every fourth month, so it spans three seasons. The response model is fitted on three folds of the training "
        "households and predicts the events of the fourth; the final check (Fig. 4) uses the held-out households.",
        "",
        md_table(fold_table(cal)),
        "",
        "Events are assigned to the fold of their start month.",
    ])
    (OUTPUTS / "lcl_split_summary.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
