"""Choose the PPO-Lagrangian multiplier and exploration settings on the ERCOT validation year (S3).

Run:  python scripts/tune_s3_rl.py   (after the tuning runs in outputs/rl/tune/<tag>/)

Candidates (agent A, ERCOT, seed 0, 800 iterations): c0 = the frozen design (constant entropy 0.01,
uncapped PID multipliers),
c1 = entropy annealed to 0, c2 = multipliers capped at 2, c3 = both, c4 = entropy annealed and integral
gain 0.005. Each deterministic policy runs on the 2023 validation months with 10 training members (the
evaluation members are kept for the final evaluation). Rule, fixed before the runs: the highest mean
reward among candidates whose violation rate is at most 10% (about the day-ahead MPC's 9.7%); if none,
the lowest violation rate. Writes outputs/s3_rl_tuning.md (copied to docs/reports).
"""
from __future__ import annotations

import shutil

import numpy as np
import pandas as pd

from run_s3_baselines import VAL_YEAR, kernel_arrays
from run_s3_rl import RL_DIR
from ttrl.env import ercot_env as ee
from ttrl.env import london_env as le
from ttrl.env.responses import TrialResponse
from ttrl.env.rewards import S2Settings
from ttrl.paths import OUTPUTS, ROOT
from ttrl.reporting import md_table
from ttrl.s3 import harness as hs
from ttrl.s3 import rl

CANDIDATES = {"c0": "frozen design", "c1": "entropy annealed to 0", "c2": "multipliers capped at 2",
              "c3": "entropy annealed + cap 2", "c4": "entropy annealed + integral gain 0.005"}
MAX_VIOLATION, VAL_MEMBERS, SEED = 0.10, 10, 20261014


def main() -> None:
    arr = kernel_arrays()
    tr, _ = le.member_split(arr.n_members)
    st = S2Settings.load()
    months = [f"{VAL_YEAR}-{m:02d}" for m in range(1, 13)]
    env = ee.ErcotTariffEnv(ee.ErcotDays.load(VAL_YEAR), TrialResponse(arr), ee.ErcotConfig.from_settings(st, months, tr), seed=0)
    members = np.random.default_rng(SEED).choice(tr, VAL_MEMBERS, replace=False)
    rows = []
    for tag, label in CANDIDATES.items():
        path = RL_DIR / "ercot_A_all_s0.pt" if tag == "c0" else RL_DIR / "tune" / tag / "ercot_A_all_s0.pt"
        if not path.exists():
            continue
        r = hs.evaluate(env, rl.load_agent(path, env), months, members)
        hist = pd.read_csv(path.with_name(path.stem + "_history.csv"))
        rows.append({"candidate": tag, "settings": label, "reward": float(r["reward"].mean()),
                     "violation_rate": float(r["violated"].mean()), "revenue_ratio": float(r["revenue_ratio"].mean()),
                     "fuel_cost": float(r["fuel_cost"].mean()), "co2_cost": float(r["co2_cost"].mean()),
                     "capacity_cost": float(r["capacity_cost"].mean()), "low_hh": float(r["low_hh"].mean()),
                     "final_lambda": float(hist["lambda_revenue"].iloc[-1])})
    tab = pd.DataFrame(rows)
    ok = tab[tab["violation_rate"] <= MAX_VIOLATION]
    chosen = ok.sort_values("reward", ascending=False).iloc[0]["candidate"] if len(ok) else \
        tab.sort_values("violation_rate").iloc[0]["candidate"]
    tab["chosen"] = tab["candidate"] == chosen
    lines = ["# PPO-Lagrangian settings chosen on the ERCOT validation year", "",
             "Generated by `python scripts/tune_s3_rl.py`. Agent A, ERCOT, seed 0, 800 iterations; deterministic policy on "
             f"the {VAL_YEAR} months with {VAL_MEMBERS} training members (evaluation members untouched). Rule fixed before "
             f"the runs: highest mean reward among candidates with violation rate <= {MAX_VIOLATION:.0%}; otherwise the "
             "lowest violation rate. Rewards and costs in 2024 US$ per month (surrogate, training reward).", "",
             md_table(tab, floatfmt="{:,.3f}"), "", f"Chosen: {chosen} ({CANDIDATES[chosen]})."]
    out = OUTPUTS / "s3_rl_tuning.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    shutil.copy(out, ROOT / "docs" / "reports" / out.name)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
