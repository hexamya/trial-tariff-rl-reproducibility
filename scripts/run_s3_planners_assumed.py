"""Overstatement of model-based planners that plan with the assumed response (S3).

Run:  python scripts/run_s3_planners_assumed.py --case london|ercot   (~1 h each)

The monthly MIP (oracle) and the day-ahead MPC of ``ttrl.s3.planners`` plan with the per-pattern effects
of the assumed response (Aalami et al. 2010 elasticity matrix; London hour categories from the pre-trial
days' load shape, ERCOT from the training years' residential load, as agent B). Self-assessed outcome: the
plans in the assumed-response environment; realised: the same plans in the trial-estimated environment
with the 50 evaluation members (London 2013, ERCOT validation year 2023; 2024 untouched). ERCOT fuel and
CO2 through ``S4Model.impact``. This tells whether the overstatement comes from the response assumption
rather than from the RL agent. Writes outputs/s3_planners_assumed_<case>.md (copied to docs/reports).
"""
from __future__ import annotations

import argparse
import shutil
import time

import numpy as np
import pandas as pd

from evaluate_s3 import S4Eval, boot_ratio, ercot_envs, london_envs, with_s4
from run_s3_baselines import kernel_arrays
from ttrl.env import assumed as am
from ttrl.env import london as ld
from ttrl.env import london_env as le
from ttrl.env.responses import AssumedResponse
from ttrl.env.rewards import S2Settings
from ttrl.paths import OUTPUTS, ROOT
from ttrl.reporting import md_table
from ttrl.s3 import harness as hs
from ttrl.s3 import patterns as pt
from ttrl.s3 import planners as pl


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", choices=["london", "ercot"], required=True)
    args = ap.parse_args()
    t0 = time.time()
    arr = kernel_arrays()
    tr, ev = le.member_split(arr.n_members)
    st = S2Settings.load()
    P = pt.candidate_patterns()
    if args.case == "london":
        trial_env, _, months, _ = london_envs(arr, tr, st)
        inp = trial_env.inputs
        pre = (inp.days["period"] == "pre").to_numpy()
        model = am.aalami_2010(am.categories_by_load(inp.baseline[pre]))
        own_env = le.LondonTariffEnv(inp, AssumedResponse(model), le.LondonConfig.from_settings(st, months, tr), seed=0)
    else:
        trial_env, own_env, months = ercot_envs(arr, tr, st)
        model = own_env.response.model
        s4 = S4Eval(trial_env.days)
    E = am.clip_effect(model.effect(P))[None]             # (1, P, 48), clipped as in AssumedResponse; no members
    rows = []
    for planner in (pl.MonthlyMIP(E, P, time_limit=120.0), pl.RollingMPC(E, P, time_limit=30.0, mip_gap=5e-3)):
        own = hs.evaluate(own_env, planner, months, [0]).assign(world="self-assessed")
        real = hs.evaluate(trial_env, planner, months, ev).assign(world="realised")    # same cached plans
        if args.case == "ercot":
            own, real = with_s4(own, own_env, s4), with_s4(real, trial_env, s4)
        rows.append(pd.concat([own, real], ignore_index=True).assign(planner=planner.name, seed=0))
        print(f"{planner.name} ({time.time() - t0:.0f} s)", flush=True)
    res = pd.concat(rows, ignore_index=True).drop(columns=["blocks", "effect", "day_idx"])
    res.to_parquet(OUTPUTS / f"s3_planners_assumed_{args.case}_episodes.parquet", index=False)
    rng = np.random.default_rng(20261015)
    metrics = [("daily_peak_cut_pct", 1.0, "daily peak cut")] if args.case == "london" else \
        [("reward", 1.0, "reward ($)"), ("s4_fuel", -1.0, "fuel saved (S4)"), ("s4_co2_t", -1.0, "CO2 saved (S4)"),
         ("monthly_net_peak_change_mw", -1.0, "net-load peak cut")]
    out = []
    for name, g in res.groupby("planner"):
        s, r = g[g["world"] == "self-assessed"], g[g["world"] == "realised"]
        for col, sign, label in metrics:
            pnt, lo, hi = boot_ratio(s, r, col, sign, rng)
            out.append({"planner": name, "outcome": label, "self-assessed": sign * s[col].mean(),
                        "realised": sign * r[col].mean(), "ratio": pnt, "ratio lo": lo, "ratio hi": hi,
                        "self violation rate": float(s["violated"].mean()),
                        "realised violation rate": float(r["violated"].mean())})
    lines = [f"# Overstatement of planners using the assumed response ({args.case})", "",
             "Generated by `python scripts/run_s3_planners_assumed.py`. Planners plan with the Aalami et al. (2010) "
             "elasticity matrix; self-assessed = plans in that environment; realised = the same plans in the "
             "trial-estimated environment with the 50 evaluation members. Intervals: bootstrap over months.", "",
             md_table(pd.DataFrame(out), floatfmt="{:,.3f}")]
    path = OUTPUTS / f"s3_planners_assumed_{args.case}.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    shutil.copy(path, ROOT / "docs" / "reports" / path.name)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
