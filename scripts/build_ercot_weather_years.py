"""ERCOT weather years for the S2 environment: hourly load, generation and plant temperatures.

Run:  python scripts/build_ercot_weather_years.py   (needs scripts/run_s4.py for 2024 first)

The 2024 gas fleet is run against the load and weather of earlier years, 2019-2022 for training and 2023 for validation;
2024 is the test year. This script assembles, for 2019-2024:

* EIA-930 ERCOT hourly demand, net generation by source group and the day-ahead demand forecast
  (PUDL; cached per year);
* plant temperatures of 2019-2023 at the 2024 fleet's plants (NOAA ISD-lite, the S4 station
  selection and gap filling, plant coordinates from EIA-860 2024; outputs tagged ``_fleet2024``);
* days with curtailed demand, to drop from training: a day is flagged when, for at least four hours,
  reported demand is more than 10% below the day-ahead forecast (the rule is fixed here, before any
  RL training; the flagged days are listed in the report);
* the share of days whose ERCOT-fleet mean daily temperature exceeds the S1 kernel's 24.7 C limit.

Writes outputs/ercot_weather_years.md and the cached files in data/interim.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from ttrl.data import eia930
from ttrl.data import weather as w
from ttrl.env.ercot import SHED_GAP, SHED_HOURS, curtailed_days
from ttrl.paths import INTERIM, OUTPUTS
from ttrl.reporting import md_table

YEARS = (2019, 2020, 2021, 2022, 2023, 2024)
WEATHER_YEARS = (2019, 2020, 2021, 2022, 2023)
FLEET_YEAR = 2024
TAG = "_fleet2024"
TZ = "America/Chicago"
KERNEL_TEMP_MAX = 24.7


def local_year(df: pd.DataFrame, year: int, col: str = "datetime_utc") -> pd.DataFrame:
    out = df.copy()
    out["ts_local"] = out[col].dt.tz_localize("UTC").dt.tz_convert(TZ).dt.tz_localize(None)
    return out[out["ts_local"].dt.year == year]


def main() -> None:
    plants = sorted(pd.read_parquet(INTERIM / f"ercot_gas_generators_{FLEET_YEAR}.parquet")["plant_id_eia"].unique())
    rows, shed_all = [], []
    for y in YEARS:
        ld = local_year(eia930.load_ba_hourly(y), y)
        sd = curtailed_days(y)
        shed_all.append(sd.assign(year=y))
        if y == FLEET_YEAR:
            tpath = INTERIM / f"plant_temperature_{y}.parquet"
        else:
            tpath = w.build_plant_temperature(y, plants, locations_year=FLEET_YEAR, tag=TAG)["temperature"]
        t = pd.read_parquet(tpath)
        t = local_year(t, y, "ts_utc")
        daily = t.groupby(t["ts_local"].dt.normalize())["temp_c"].mean()
        gas_share = ld["gas"].sum() / ld["net_generation"].sum()
        rows.append({"year": y, "role": "test" if y == FLEET_YEAR else ("validation" if y == 2023 else "training"),
                     "hours": len(ld), "missing demand h": int(ld["demand"].isna().sum()),
                     "demand TWh": ld["demand"].sum() / 1e6, "peak MW": ld["demand"].max(),
                     "gas share %": 100 * gas_share, "curtailed days": len(sd),
                     "plants with temperature": int(t["plant_id_eia"].nunique()),
                     "filled temp %": 100 * float(t["filled"].mean()),
                     "days > 24.7 C %": 100 * float((daily > KERNEL_TEMP_MAX).mean()),
                     "max daily mean C": float(daily.max())})
        print(f"{y}: done", flush=True)
    tab = pd.DataFrame(rows)
    shed = pd.concat(shed_all, ignore_index=True)
    shed_txt = md_table(shed.assign(date=shed["date"].dt.date.astype(str))[["year", "date", "hours", "max_gap"]],
                        floatfmt="{:.2f}") if len(shed) else "None."
    report = "\n".join([
        "# ERCOT weather years for S2 (2019-2024)",
        "",
        "Generated by `python scripts/build_ercot_weather_years.py`. EIA-930 via PUDL (adjusted demand, net "
        "generation by source group, day-ahead forecast); plant temperatures from NOAA ISD-lite with the S4 "
        f"station selection at the {len(plants)} plants of the {FLEET_YEAR} ERCOT gas fleet (coordinates from EIA-860 "
        f"{FLEET_YEAR}). Years are local (US Central). Training uses 2019–2022 and validation uses 2023.",
        "",
        md_table(tab, floatfmt="{:,.1f}"),
        "",
        f"Curtailed-demand days (dropped from training): at least {SHED_HOURS} hours with reported demand more than "
        f"{100 * SHED_GAP:.0f}% below the day-ahead forecast. The rule was fixed before looking at the result.",
        "",
        shed_txt,
        "",
        f"'days > 24.7 C': share of days whose mean temperature over the fleet's plants exceeds the S1 kernel's "
        "upper limit (London daily means, -1.6 to 24.7 C).",
    ])
    OUTPUTS.mkdir(parents=True, exist_ok=True)
    (OUTPUTS / "ercot_weather_years.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
