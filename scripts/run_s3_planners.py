"""S3 optimisation baselines (monthly MIP oracle, day-ahead MPC) with the trial-estimated response.

Run:  python scripts/run_s3_planners.py [--case london|ercot|both]   (long: hours; run in the background)

Both plan with per-pattern effects of all 150 training ensemble members (the members the RL agents train
on): objective averaged over them, revenue band required for 11 representative members spanning their
revenue response (``planners.revenue_scenarios``). Evaluated with the 50 evaluation members: London on the 12 months of
2013, ERCOT on the validation year 2023 (the test year 2024 is not touched). The planners need no
calibration, so London needs no cross-fitting. Writes outputs/s3_planners.md (copied to docs/reports),
outputs/s3_planners_episodes.parquet and the solver logs.
"""
from __future__ import annotations

import argparse
import shutil
import time

import numpy as np
import pandas as pd

from run_s3_baselines import VAL_YEAR, kernel_arrays, summary
from ttrl.env import ercot_env as ee
from ttrl.env import fastkernel as fk
from ttrl.env import london as ld
from ttrl.env import london_env as le
from ttrl.env.responses import TrialResponse
from ttrl.env.rewards import S2Settings
from ttrl.paths import OUTPUTS, ROOT
from ttrl.reporting import md_table
from ttrl.s3 import harness as hs
from ttrl.s3 import patterns as pt
from ttrl.s3 import planners as pl

MIP_TIME, MPC_TIME, MPC_GAP = 120.0, 30.0, 5e-3


def planners(arr, tr):
    plan_m = np.asarray(tr)
    P = pt.candidate_patterns()
    E = pt.pattern_effects(P, fk.KernelArrays(arr.in_event[plan_m], arr.dur_dev[plan_m], arr.window[plan_m]))
    return [pl.MonthlyMIP(E, P, time_limit=MIP_TIME), pl.RollingMPC(E, P, time_limit=MPC_TIME, mip_gap=MPC_GAP)]


def run(env, pols, months, ev, case, t0) -> tuple[pd.DataFrame, pd.DataFrame]:
    rows, logs = [], []
    for pol in pols:
        for m in months:
            rows.append(hs.evaluate(env, pol, [m], ev).assign(family=pol.name, case=case))
            print(f"{case} {pol.name} {m} ({time.time() - t0:.0f} s)", flush=True)
        logs.append(pd.DataFrame(pol.log).assign(family=pol.name, case=case))
    return pd.concat(rows, ignore_index=True), pd.concat(logs, ignore_index=True)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", choices=["london", "ercot", "both"], default="both")
    ap.add_argument("--report-only", action="store_true", help="rebuild the report from the saved episode and solver files")
    args = ap.parse_args()
    tag = "" if args.case == "both" else f"_{args.case}"
    if args.report_only:
        write_report(pd.read_parquet(OUTPUTS / f"s3_planners_episodes{tag}.parquet"),
                     pd.read_csv(OUTPUTS / f"s3_planners_solver_log{tag}.csv"), tag)
        return
    t0 = time.time()
    arr = kernel_arrays()
    tr, ev = le.member_split(arr.n_members)
    st = S2Settings.load()
    res, logs = [], []
    if args.case in ("london", "both"):
        inp = ld.LondonInputs.load()
        months = sorted(inp.days.loc[inp.days["period"] == "trial", "month"].unique())
        env = le.LondonTariffEnv(inp, arr, le.LondonConfig.from_settings(st, months, tr), seed=0)
        r, lg = run(env, planners(arr, tr), months, ev, "London", t0)
        res.append(r)
        logs.append(lg)
    if args.case in ("ercot", "both"):
        months = [f"{VAL_YEAR}-{m:02d}" for m in range(1, 13)]
        env = ee.ErcotTariffEnv(ee.ErcotDays.load(VAL_YEAR), TrialResponse(arr), ee.ErcotConfig.from_settings(st, months, tr), seed=0)
        r, lg = run(env, planners(arr, tr), months, ev, "ERCOT", t0)
        res.append(r)
        logs.append(lg)
    res = pd.concat(res, ignore_index=True).drop(columns=["blocks", "effect", "day_idx"], errors="ignore")
    logs = pd.concat(logs, ignore_index=True)
    res.to_parquet(OUTPUTS / f"s3_planners_episodes{tag}.parquet", index=False)
    logs.to_csv(OUTPUTS / f"s3_planners_solver_log{tag}.csv", index=False)
    write_report(res, logs, tag)


def write_report(res: pd.DataFrame, logs: pd.DataFrame, tag: str) -> None:
    summ = summary(res)
    solver = logs.groupby(["case", "family"]).agg(solves=("status", "size"), optimal=("status", lambda s: float((s == 0).mean())),
                                                  time_limit_hit=("status", lambda s: float((s == 1).mean())),
                                                  infeasible=("objective", lambda o: float(o.isna().mean()))).reset_index()
    lines = ["# S3 optimisation baselines (trial-estimated response)", "",
             "Generated by `python scripts/run_s3_planners.py`. Planning with the 150 training members (revenue band for 11 "
             "representative members, "
             "objective averaged); evaluation with the 50 evaluation members. MIP: whole month with the actual load "
             f"(oracle; time limit {MIP_TIME:.0f} s). MPC: re-plans each day with known load and forecasts, tomorrow "
             f"integer, later days relaxed (time limit {MPC_TIME:.0f} s, gap {MPC_GAP:.1%}).", ""]
    for case in summ["case"].unique():
        lines += [f"## {case}", "", md_table(summ[summ["case"] == case].dropna(axis=1, how="all"), floatfmt="{:,.3f}"), ""]
    lines += ["## Solver", "", md_table(solver, floatfmt="{:.3f}"),
              "", "Status 0 = optimal within the gap, 1 = time limit (best plan found is used)."]
    out = OUTPUTS / f"s3_planners{tag}.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    shutil.copy(out, ROOT / "docs" / "reports" / out.name)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
